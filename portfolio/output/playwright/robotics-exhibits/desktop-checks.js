async (page) => {
  const errors = [], failedRequests = [], warnings = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('requestfailed', r => failedRequests.push({url:r.url(),error:r.failure()}));
  page.on('console', m => { if(m.type()==='warning') warnings.push(m.text()); });
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const selected = name => page.getByRole('button',{name,exact:true});
  const label = name => page.locator('[data-selected]').filter({has:page.locator('strong',{hasText:name})});
  await page.locator('main[data-phase=workshop]').waitFor();
  await page.mouse.move(560,410);
  await page.waitForFunction(() => document.querySelector('[data-attention=true] strong')?.textContent === 'Gesture Rover');
  await page.screenshot({path:'output/playwright/robotics-exhibits/03-rover-hover.png'});
  await page.mouse.click(560,410);
  assert(await selected('Gesture Rover').getAttribute('aria-pressed') === 'true', 'Robot mesh did not select Gesture Rover');
  assert(await label('Gesture Rover').getAttribute('data-selected') === 'true','Robot selection did not reach the visible scene');
  await page.screenshot({path:'output/playwright/robotics-exhibits/04-rover-selected.png'});
  await page.mouse.move(1020,435);
  await page.waitForFunction(() => document.querySelector('[data-attention=true] strong')?.textContent === 'Guiding Hands');
  await page.mouse.click(1020,435);
  assert(await selected('Guiding Hands').getAttribute('aria-pressed') === 'true', 'Monitor mesh did not select Guiding Hands');
  assert(await selected('Gesture Rover').getAttribute('aria-pressed') === 'false', 'Two selections active');
  await page.screenshot({path:'output/playwright/robotics-exhibits/05-hands-selected.png'});
  // Keyboard reaches both controls in document order; focus alone does not select.
  await page.getByRole('button',{name:'Back to Desk'}).focus();
  await page.keyboard.press('Tab');
  assert(await selected('Gesture Rover').evaluate(b=>b===document.activeElement), 'Tab did not reach Rover');
  await page.mouse.move(1550,850);
  assert(await label('Gesture Rover').getAttribute('data-attention') === 'true','Pointer leaving erased keyboard focus highlight');
  await page.keyboard.press('Enter');
  assert(await selected('Gesture Rover').getAttribute('aria-pressed') === 'true','Enter did not select Rover');
  await page.keyboard.press('Tab'); await page.keyboard.press('Space');
  assert(await selected('Guiding Hands').getAttribute('aria-pressed') === 'true','Space did not select Guiding Hands');
  await page.screenshot({path:'output/playwright/robotics-exhibits/06-keyboard.png'});
  // Drag starts on an unselected mesh and must orbit without selecting it.
  const beforeDrag = await page.locator('canvas').getAttribute('data-camera-position');
  await page.mouse.move(560,410); await page.mouse.down(); await page.mouse.move(640,440,{steps:12}); await page.mouse.up();
  assert(await selected('Gesture Rover').getAttribute('aria-pressed') === 'false','Drag selected Rover');
  const afterDrag = await page.locator('canvas').getAttribute('data-camera-position');
  assert(beforeDrag !== afterDrag, 'Drag did not orbit');
  await page.keyboard.press('Escape');
  await page.locator('main[data-phase=desk][data-world=desk]').waitFor({timeout:30000});
  assert(await page.getByRole('button',{name:'Visit robotics workshop'}).evaluate(b=>b===document.activeElement),'Return focus lost');
  await page.screenshot({path:'output/playwright/robotics-exhibits/07-return.png'});
  await page.getByRole('button',{name:'Visit robotics workshop'}).click();
  await page.locator('main[data-phase=workshop]').waitFor({timeout:30000});
  assert(await selected('Gesture Rover').getAttribute('aria-pressed') === 'false' && await selected('Guiding Hands').getAttribute('aria-pressed') === 'false','Selection leaked across visits');
  const environment = await page.evaluate(() => { const c=document.querySelector('canvas'),gl=c.getContext('webgl2'),d=gl.getExtension('WEBGL_debug_renderer_info'); return {renderer:gl.getParameter(d.UNMASKED_RENDERER_WEBGL),userAgent:navigator.userAgent,viewport:[innerWidth,innerHeight],canvases:document.querySelectorAll('canvas').length,drawCalls:c.dataset.drawCalls,triangles:c.dataset.triangles}; });
  assert(!errors.length, JSON.stringify(errors));
  return {checks:{meshHoverBoth:'Pass',meshSelectBoth:'Pass',singleSelection:'Pass',keyboardTabEnterSpace:'Pass',focusSurvivesPointerLeave:'Pass',dragWithoutSelection:'Pass',escapeAndRestoredFocus:'Pass',repeatVisitResetsSelection:'Pass'}, environment,errors,failedRequests,warnings};
}
